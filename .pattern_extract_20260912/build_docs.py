#!/usr/bin/env python3
import html
import json
import re
from pathlib import Path

BASE = Path(__file__).parent
R = json.loads((BASE / "normalized.json").read_text(encoding="utf-8"))
V = [r for r in R if r["valid"]]
M = {r["folder"].split("_", 1)[0]: r for r in R}


def e(s):
    return html.escape(str(s), quote=True)


def path(code, media=False):
    r = M[code]
    return r["source_media" if media else "source_info"]


def sources(codes, media=False):
    return "<ul>" + "".join(f"<li>{e(path(c, media))}</li>" for c in codes) + "</ul>"


def pattern(no, name, plain, fit, notfit, warning, codes, media=False, status="本期可用"):
    return (f"<h2>规律 {no}：【{e(name)}】（状态：{e(status)}）</h2>"
            f"<p><b>大白话解释：</b>{e(plain)}</p>"
            f"<p><b>适合什么内容：</b>{e(fit)}</p>"
            f"<p><b>不适合什么内容：</b>{e(notfit)}</p>"
            f"<p><b>不可照搬点：</b>{e(warning)}</p>"
            f"<p><b>来源素材：</b></p>{sources(codes, media)}")


def write(name, body):
    (BASE / "out").mkdir(exist_ok=True)
    (BASE / "out" / f"{name}.xml").write_text(f"<title>{e(name)}</title>{body}", encoding="utf-8")


